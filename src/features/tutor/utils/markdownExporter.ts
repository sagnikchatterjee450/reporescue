/**
 * Generates a comprehensive, clean ONBOARDING.md from a RepoModel
 */
import { RepoModel } from '../types';

export function generateOnboardingMarkdown(model: RepoModel): string {
  const parts: string[] = [];

  parts.push(`# Developer Onboarding Guide: ${model.repoName}`);
  parts.push(`*Generated by RepoRescue Tutor Copilot for [${model.owner}/${model.repoName}](${model.repoUrl})*`);
  parts.push('');

  // 1. Executive Summary & Audience
  parts.push('## 1. Overview');
  parts.push(model.summary);
  parts.push('');
  parts.push(`**Target Audience / Contributor Profile:** ${model.intendedAudience}`);
  parts.push('');

  // 2. Tech Stack
  parts.push('## 2. Tech Stack & Dependencies');
  parts.push('| Technology | Category | Why We Use It |');
  parts.push('| :--- | :--- | :--- |');
  for (const item of model.techStack) {
    parts.push(`| **${item.name}** | ${item.category} | ${item.whyUsed} |`);
  }
  parts.push('');

  // 3. Entry Points & Architecture
  parts.push('## 3. Entry Points & Core Architecture');
  parts.push('### Key Entry Files');
  for (const ep of model.entryPoints) {
    parts.push(`- \`${ep.file}\`: ${ep.purpose}`);
    if (ep.exports && ep.exports.length > 0) {
      parts.push(`  - Key exports: \`${ep.exports.join('`, `')}\``);
    }
  }
  parts.push('');

  parts.push('### System Architecture Diagram');
  parts.push('```mermaid');
  parts.push(model.diagrams.systemOverviewMermaid.trim());
  parts.push('```');
  parts.push('');

  parts.push('### Core Modules');
  for (const mod of model.modules) {
    parts.push(`#### ${mod.name} (\`${mod.id}\`)`);
    parts.push(`${mod.purpose}`);
    parts.push(`- **Key Files:** ${mod.keyFiles.map((f) => `\`${f}\``).join(', ')}`);
    if (mod.dependsOn && mod.dependsOn.length > 0) {
      parts.push(`- **Depends on:** ${mod.dependsOn.join(', ')}`);
    }
    parts.push('');
  }

  // 4. Setup & Running Local Environment
  parts.push('## 4. Local Development Setup');
  for (const step of model.setupSteps) {
    parts.push(`### Step: ${step.category.toUpperCase()}`);
    parts.push(`${step.description}`);
    parts.push('```bash');
    parts.push(step.command);
    parts.push('```');
    if (step.commonFailures && step.commonFailures.length > 0) {
      parts.push('**Troubleshooting Tips:**');
      for (const fail of step.commonFailures) {
        parts.push(`- ${fail}`);
      }
    }
    parts.push('');
  }

  // 5. Configuration & Environment Variables
  if (model.configAndEnvVars && model.configAndEnvVars.length > 0) {
    parts.push('## 5. Environment Variables & Configuration');
    parts.push('| Variable | Required | Default | Purpose / Example |');
    parts.push('| :--- | :--- | :--- | :--- |');
    for (const v of model.configAndEnvVars) {
      parts.push(`| \`${v.name}\` | ${v.required ? 'Yes' : 'No'} | \`${v.defaultValue || 'none'}\` | ${v.purpose} (e.g. \`${v.example}\`) |`);
    }
    parts.push('');
  }

  // 6. Guided Tour Sequence
  parts.push('## 6. Recommended Reading Order (Guided Tour)');
  for (const tour of model.guidedTour) {
    parts.push(`### Step ${tour.stepNumber}: ${tour.title} (~${tour.minutes} mins)`);
    parts.push(`*Best for: ${tour.difficulty.replace(/_/g, ' ')}*`);
    parts.push(`- **Files to open:** ${tour.files.map((f) => `\`${f}\``).join(', ')}`);
    parts.push(`- **Why it matters:** ${tour.whyItMatters}`);
    parts.push('- **What to notice:**');
    for (const notice of tour.whatToNotice) {
      parts.push(`  - ${notice}`);
    }
    parts.push('');
  }

  // 7. Code Conventions & Gotchas
  parts.push('## 7. Conventions & Known Gotchas');
  if (model.codeConventions && model.codeConventions.length > 0) {
    parts.push('### Code Conventions');
    for (const conv of model.codeConventions) {
      parts.push(`- **${conv.rule}**: ${conv.context}`);
      if (conv.example) parts.push(`  - Example: \`${conv.example}\``);
    }
    parts.push('');
  }

  if (model.gotchas && model.gotchas.length > 0) {
    parts.push('### Known Gotchas & Pitfalls');
    for (const gotcha of model.gotchas) {
      parts.push(`- **⚠️ ${gotcha.title}**: ${gotcha.description}`);
      parts.push(`  - **Mitigation:** ${gotcha.mitigation}`);
    }
    parts.push('');
  }

  // 8. First Contributions
  if (model.firstContributions && model.firstContributions.length > 0) {
    parts.push('## 8. Suggested First Contributions');
    for (const task of model.firstContributions) {
      parts.push(`### [${task.difficulty.toUpperCase()}] ${task.title}`);
      parts.push(`*Estimated time: ${task.estimatedMinutes} minutes*`);
      parts.push(`- **Why start here:** ${task.whyGoodFirstIssue}`);
      parts.push(`- **Files involved:** ${task.involvedFiles.map((f) => `\`${f}\``).join(', ')}`);
      parts.push(`- **Testing instructions:** ${task.testInstructions}`);
      parts.push('');
    }
  }

  // 9. Glossary
  if (model.keyConceptsAndGlossary && model.keyConceptsAndGlossary.length > 0) {
    parts.push('## 9. Project Glossary');
    for (const item of model.keyConceptsAndGlossary) {
      parts.push(`- **${item.term}**: ${item.definition} *(used in ${item.whereUsed})*`);
    }
    parts.push('');
  }

  return parts.join('\n');
}

export function downloadMarkdownFile(content: string, filename = 'ONBOARDING.md') {
  const blob = new Blob([content], { type: 'text/markdown;charset=utf-8' });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}
